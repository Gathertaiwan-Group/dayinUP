-- ---------------------------------------------------------------- media
create table if not exists site_dayinup.media (
  id            bigint generated by default as identity (start with 1000000) primary key, -- WP attachment ID
  slug          text,
  title         text,
  alt_text      text not null default '',
  caption_html  text not null default '',
  description_html text not null default '',
