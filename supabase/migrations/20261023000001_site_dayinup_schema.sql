  discount_type  text not null check (discount_type in ('percent','fixed_amount','fixed_price')),
  discount_value numeric(12,4) not null,           -- percent: 10 = 10% off (9折); fixed_price: unit price
  starts_at      timestamptz,
  ends_at        timestamptz,
  active         boolean not null default true,
  source         text not null default 'manual',  -- variation_label = parsed from old WP variation name
  priority       int not null default 0
);
create index if not exists qdr_product_idx on site_dayinup.quantity_discount_rules(product_id);
create index if not exists qdr_variation_idx on site_dayinup.quantity_discount_rules(variation_id);
