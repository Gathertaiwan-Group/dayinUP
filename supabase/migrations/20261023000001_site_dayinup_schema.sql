-- DayinUP (dayinup.com) — WordPress/WooCommerce → Supabase schema
-- Scope: ONLY schema site_dayinup. Never touches other schemas.
-- Convention: primary keys keep the original WordPress IDs (post ID, term_id, user ID,
-- order ID, ...). Identity sequences start at 1,000,000 so rows created on the new site
-- never collide with WP IDs that will be imported later (orders, customers, coupons).

-- ---------------------------------------------------------------- helpers
create or replace function site_dayinup.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- ---------------------------------------------------------------- site settings
create table if not exists site_dayinup.settings (
  key         text primary key,
  value       jsonb not null default 'null'::jsonb,
  is_public   boolean not null default true,       -- readable by anon (front-end)
  description text,
  updated_at  timestamptz not null default now()
);

-- registry of content types / taxonomies (mirrors WP register_post_type / register_taxonomy)
create table if not exists site_dayinup.post_types (
