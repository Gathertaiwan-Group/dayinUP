-- ---------------------------------------------------------------- updated_at triggers
do $$
declare t text;
begin
  foreach t in array array['settings','media','terms','posts','menus','products','product_variations','carts','forms'] loop
    execute format('drop trigger if exists set_updated_at on site_dayinup.%I', t);
    execute format('create trigger set_updated_at before update on site_dayinup.%I for each row execute function site_dayinup.set_updated_at()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- RLS
-- Every table has RLS. anon/authenticated may only SELECT published public content.
-- All writes go through the server (service_role bypasses RLS) after admin verification.
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'site_dayinup' loop
    execute format('alter table site_dayinup.%I enable row level security', t);
  end loop;
end $$;

-- public read policies
do $$
declare
  pub text[] := array['post_types','taxonomies','authors','media','media_url_map','terms','post_terms',
                      'menus','menu_items','product_terms','product_images','attributes','product_attributes',
                      'redirects','legacy_urls'];
  t text;
begin
  foreach t in array pub loop
    execute format('drop policy if exists public_read on site_dayinup.%I', t);
    execute format('create policy public_read on site_dayinup.%I for select to anon, authenticated using (true)', t);
  end loop;
end $$;

drop policy if exists public_read on site_dayinup.settings;
create policy public_read on site_dayinup.settings for select to anon, authenticated using (is_public);

drop policy if exists public_read on site_dayinup.posts;
create policy public_read on site_dayinup.posts for select to anon, authenticated
  using (status = 'publish' and password is null);

drop policy if exists public_read on site_dayinup.comments;
create policy public_read on site_dayinup.comments for select to anon, authenticated using (status = 'approved');

drop policy if exists public_read on site_dayinup.products;
create policy public_read on site_dayinup.products for select to anon, authenticated
  using (status = 'publish' and catalog_visibility <> 'hidden');

drop policy if exists public_read on site_dayinup.product_variations;
create policy public_read on site_dayinup.product_variations for select to anon, authenticated
  using (status = 'publish' and exists (
    select 1 from site_dayinup.products p where p.id = product_id and p.status = 'publish'));

drop policy if exists public_read on site_dayinup.quantity_discount_rules;
create policy public_read on site_dayinup.quantity_discount_rules for select to anon, authenticated using (active);

drop policy if exists public_read on site_dayinup.forms;
create policy public_read on site_dayinup.forms for select to anon, authenticated using (status = 'published');

