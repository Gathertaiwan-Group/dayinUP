  label        text not null,
  rest_base    text,
  hierarchical boolean not null default false,
  is_builtin   boolean not null default false,
  public       boolean not null default true,
  supports     jsonb not null default '{}'::jsonb
);

create table if not exists site_dayinup.taxonomies (
  name         text primary key,                  -- category, post_tag, product_cat, ...
  label        text not null,
  hierarchical boolean not null default false,
  object_types text[] not null default '{}',
  rest_base    text
);

