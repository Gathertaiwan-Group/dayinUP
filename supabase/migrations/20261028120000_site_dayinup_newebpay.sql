-- NewebPay MPG integration (藍新金流). Scope: ONLY schema site_dayinup.
-- 1) orders.stock_reduced: WooCommerce `_order_stock_reduced` — claimed atomically (false→true) so a repeated
--    payment notification can never reduce stock twice.
-- 2) payment_notifications: log of every verified inbound NewebPay call (notify / customer) and its outcome.
--    Private table: RLS on, no policies, anon/authenticated revoked => service_role only.

alter table site_dayinup.orders add column if not exists stock_reduced boolean not null default false;

create table if not exists site_dayinup.payment_notifications (
  id                bigint generated by default as identity primary key,
  gateway           text not null default 'newebpay',
  kind              text not null,                 -- notify | customer
  order_id          bigint references site_dayinup.orders(id) on delete cascade,
  merchant_order_no text,
  trade_no          text,
  status            text,                          -- NewebPay Status (SUCCESS / error code)
  amount            numeric(12,2),
  outcome           text not null,                 -- paid | failed | on-hold | duplicate | ignored | unknown_order | amount_mismatch | order_no_mismatch
  result            jsonb,
  created_at        timestamptz not null default now()
);
create index if not exists payment_notifications_order_idx on site_dayinup.payment_notifications(order_id, created_at desc);
create index if not exists payment_notifications_mon_idx on site_dayinup.payment_notifications(merchant_order_no);
create index if not exists orders_pending_gateway_idx on site_dayinup.orders(status, payment_method, date_modified) where status = 'pending';

alter table site_dayinup.payment_notifications enable row level security;
revoke all on site_dayinup.payment_notifications from anon, authenticated;
grant all on site_dayinup.payment_notifications to service_role;
grant all on all sequences in schema site_dayinup to service_role;
